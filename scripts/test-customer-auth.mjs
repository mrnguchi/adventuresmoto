import assert from 'node:assert/strict';
import { randomBytes, createHash } from 'node:crypto';
import env from '@next/env';
import mariadb from 'mariadb';
env.loadEnvConfig(process.cwd());
const url = new URL(process.env.DATABASE_URL);
assert.ok(['localhost','127.0.0.1'].includes(url.hostname));
const db = await mariadb.createConnection({host:url.hostname,port:Number(url.port || 3306),user:decodeURIComponent(url.username),password:decodeURIComponent(url.password),database:url.pathname.slice(1)});
const origin='http://localhost:3000';
const email=`customer-test-${randomBytes(8).toString('hex')}@example.invalid`;
const password=randomBytes(20).toString('hex');
let cookie='';
const post=(action,body,extra={})=>fetch(`${origin}/api/account/${action}`,{method:'POST',headers:{origin,'content-type':'application/json',cookie,...extra},body:JSON.stringify(body)});
try {
  assert.equal((await post('profile',{firstName:'A',lastName:'B'})).status,401);
  const input={email,password,passwordConfirmation:password,firstName:'Customer',lastName:'Test',termsAccepted:true,roles:['ADMIN']};
  assert.equal((await post('signup',input,{origin:'https://example.invalid'})).status,403);
  assert.equal((await post('signup',{...input,passwordConfirmation:'wrong'})).status,400);
  const created=await post('signup',input);
  assert.equal(created.status,200,await created.clone().text());
  cookie=created.headers.get('set-cookie').split(';')[0];
  assert.ok(created.headers.get('set-cookie').includes('HttpOnly'));
  const user=(await created.json()).user;
  assert.equal(user.email,email); assert.equal(user.passwordHash,undefined);
  const [saved]=await db.query('SELECT passwordHash,emailVerifiedAt FROM users WHERE id=?',[user.id]);
  assert.ok(saved.passwordHash.startsWith('scrypt$')); assert.equal(saved.emailVerifiedAt,null);
  assert.equal((await db.query('SELECT * FROM user_roles WHERE userId=?',[user.id])).length,0);
  const session=await (await fetch(`${origin}/api/account/session`,{headers:{cookie}})).json();
  assert.equal(session.user.id,user.id);
  assert.equal((await post('signup',input)).status,409);
  const profile=await post('profile',{id:0,email:'ignored@example.invalid',firstName:'Updated',lastName:'Customer',phone:'+234123456'});
  assert.equal(profile.status,200); const updated=(await profile.json()).user; assert.equal(updated.id,user.id); assert.equal(updated.email,email); assert.equal(updated.firstName,'Updated');
  const admin=await fetch(`${origin}/api/admin/products/save`,{method:'POST',headers:{origin,'content-type':'application/json',cookie},body:'{}'});
  assert.equal(admin.status,401);
  assert.equal((await post('logout',{})).status,200);
  assert.equal((await post('profile',{firstName:'A',lastName:'B'})).status,401);
  assert.equal((await post('login',{email,password:'incorrect'})).status,401);
  const login=await post('login',{email:email.toUpperCase(),password}); assert.equal(login.status,200,await login.clone().text());
  cookie=login.headers.get('set-cookie').split(';')[0];
  await db.query('UPDATE users SET disabledAt=NOW(3) WHERE id=?',[user.id]);
  assert.equal((await post('profile',{firstName:'A',lastName:'B'})).status,401);
  await db.query('UPDATE users SET disabledAt=NULL WHERE id=?',[user.id]);
  await db.query('UPDATE customer_sessions SET expiresAt=DATE_SUB(NOW(),INTERVAL 1 DAY) WHERE userId=?',[user.id]);
  assert.equal((await post('profile',{firstName:'A',lastName:'B'})).status,401);
  for(let i=0;i<6;i++) assert.equal((await post('login',{email,password:'incorrect'})).status,401);
  assert.equal((await post('login',{email,password:'incorrect'})).status,429);
  console.log('PASS: registration, validation, duplicate email, hashing, session, profile ownership, admin isolation, logout, login, disabled/expired sessions and throttling.');
} finally {
  await db.query('DELETE FROM users WHERE email=?',[email]);
  await db.query('DELETE FROM customer_auth_attempts WHERE `key`=?',[createHash('sha256').update(email).digest('hex')]);
  await db.end();
}
